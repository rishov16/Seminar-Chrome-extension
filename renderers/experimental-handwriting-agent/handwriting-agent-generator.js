// Fills gaps in the HandwritingAgent transcript bank on demand by calling
// Gemini with the paper's own SYSTEM_PROMPT — the piece
// handwriting-agent-transcripts.js's own header comment already anticipated
// ("No API key is available in this environment... if a key is ever
// supplied, this bank is the piece a live per-character API route would
// replace") but couldn't build without live API access. This project now
// has one (lib/llm-client.js, reused for Head/Narrator/Live), closing that
// gap.
//
// Scoped to prose characters only for now — the literal on-board text of
// prose/bullet blocks. Equation leaves come from MathJax's own layout
// extraction (mathjax-layout.js), not the raw LaTeX string (a macro like
// \alpha isn't the character 'a','l','p','h','a' — it's a single Greek
// glyph resolved by MathJax), so prewarming those correctly would need a
// heavier extractMathLayout-based scan; left as a follow-up, not attempted
// here.
//
// Runs as a best-effort background prefetch, never a render-path
// dependency: a character not yet generated by the time its slide plays
// just uses the existing plain-text fallback (agent-prose-word.js's
// buildFallbackChar) exactly as it did before this module existed — pure
// upside, no new failure mode if generation is slow, offline, or fails for
// a given character.
import { generateText, LlmError } from '../../lib/llm-client.js';
import { getLocal, setLocal } from '../../lib/storage.js';
import { SYSTEM_PROMPT } from './handwriting-agent-transcripts.js?v=11';
import { hasAgentGlyph, registerGeneratedTranscript } from './handwriting-agent.js?v=25';

const STORAGE_KEY = 'generatedHandwritingGlyphs'; // chrome.storage.local: { [char]: transcriptXml }

// Characters that failed to generate or parse this session — not retried
// on every slide load, only cleared by a fresh page load (a genuinely bad
// character isn't likely to succeed on a bare retry, and retrying silently
// forever would burn API calls for no benefit).
const attempted = new Set();

let loadPersistedPromise = null;
function loadPersisted() {
  if (!loadPersistedPromise) {
    loadPersistedPromise = getLocal(STORAGE_KEY, {}).then((stored) => {
      Object.entries(stored).forEach(([char, xml]) => registerGeneratedTranscript(char, xml));
      return stored;
    });
  }
  return loadPersistedPromise;
}

// Spells out this bank's actual authored coordinate convention (see
// handwriting-agent-transcripts.js's header comment) explicitly, since
// SYSTEM_PROMPT's own "Canvas Size: 1000x500" line alone doesn't pin a
// per-character cell size — without this, a freshly generated glyph could
// land on a wildly different absolute scale than its neighbors and render
// disproportionately large/small within the same word (each glyph's own
// proportions would still be internally correct — parseTranscript normalizes
// by each glyph's own bbox — but cross-character consistency needs a shared
// convention, which only this explicit instruction provides).
function buildUserPrompt(char) {
  return `Character to draw: "${char}"

Author this single character's stroke geometry inside ONE grid cell using this exact convention (matching every other character already in this bank, not the full 1000x500 canvas): x roughly 0 to 60, y roughly 0 to 110, y increasing downward (screen convention), baseline at approximately y=86, descenders (if any) below the baseline. Follow the system instructions and return exactly one <answer><char label="${char}">...</char></answer> block for this character only.`;
}

async function generateOne(char, apiKey) {
  let raw;
  try {
    raw = await generateText(apiKey, { systemPrompt: SYSTEM_PROMPT, userContent: buildUserPrompt(char) });
  } catch (e) {
    if (e instanceof LlmError) {
      console.warn(`[handwriting-agent-generator] generation failed for ${JSON.stringify(char)}: ${e.message}`);
      return null;
    }
    throw e;
  }
  return registerGeneratedTranscript(char, raw) ? raw : null;
}

/**
 * Best-effort background prewarm: generates and caches a transcript for
 * every character in `chars` not already covered (static bank, previously
 * generated/persisted, or already attempted-and-failed this session).
 * Never throws on an individual character's failure.
 * @param {Iterable<string>} chars
 * @param {string} apiKey
 */
export async function ensureGlyphsGenerated(chars, apiKey) {
  if (!apiKey) return;
  await loadPersisted();

  const unique = [...new Set(chars)].filter((c) => c.trim() && !hasAgentGlyph(c) && !attempted.has(c));
  if (!unique.length) return;
  unique.forEach((c) => attempted.add(c));

  const persistedUpdates = {};
  for (const char of unique) {
    // Sequential, not Promise.all — this is a background prefetch, not
    // latency-sensitive, and avoids bursting many concurrent requests
    // against the same API key while a seminar is also being generated.
    // eslint-disable-next-line no-await-in-loop
    const raw = await generateOne(char, apiKey);
    if (raw) persistedUpdates[char] = raw;
  }
  if (Object.keys(persistedUpdates).length) {
    const stored = await getLocal(STORAGE_KEY, {});
    await setLocal(STORAGE_KEY, { ...stored, ...persistedUpdates });
  }
}

// $...$-wrapped spans render through the equation path (MathJax), never
// this one — mirrors agent-chalkboard-renderer.js's own tokenizeProse split
// (`/(\$[^$]+\$|\s+)/`), so raw LaTeX delimiter/macro characters never get
// mistaken for literal prose ink.
function stripInlineMath(text) {
  return (text || '').split(/\$[^$]+\$/).join(' ');
}

/**
 * Every literal on-board character from a slide's prose/bullet-item text —
 * never narrationText (spoken, not written) and never equation latex (needs
 * MathJax's own leaf extraction to resolve correctly, not a raw character
 * scan — see module header).
 * @param {import('../../lib/seminar-json-schema.js').Slide} slide
 * @returns {Set<string>}
 */
export function collectProseChars(slide) {
  const chars = new Set();
  (slide.boardContent || []).forEach((block) => {
    if (block.type === 'prose') [...stripInlineMath(block.text)].forEach((c) => chars.add(c));
    if (block.type === 'bullet-list') (block.items || []).forEach((item) => [...stripInlineMath(item.text)].forEach((c) => chars.add(c)));
  });
  return chars;
}
